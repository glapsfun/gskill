// markdown.go derives Starlight frontmatter from a docs page: the title from
// its first H1, the description from its first prose paragraph, and the edit
// link from its source path.

package docsite

import (
	"bytes"
	"encoding/json"
	"fmt"
	"regexp"
	"strconv"
	"strings"
	"unicode/utf8"
)

// maxDescription caps the description, in runes, for search results and link
// previews.
const maxDescription = 160

// generatedMarker opens the banner cmd/gen-reference writes at the top of the
// command and exit-code reference pages.
const generatedMarker = "<!-- GENERATED by cmd/gen-reference"

// generatedNote replaces the edit link on generated pages, which must be
// regenerated rather than edited.
const generatedNote = ":::note\nThis page is generated from the CLI. Do not edit it by hand; run\n" +
	"`go run ./cmd/gen-reference` and commit the result.\n:::"

// Page is a docs page split into Starlight frontmatter fields and body.
type Page struct {
	Title       string
	Description string
	// EditURL is the GitHub edit link; empty renders editUrl: false.
	EditURL string
	// Body is the Markdown after the H1, leading blank lines removed.
	Body string
}

// ParsePage extracts the frontmatter fields from src. rel is the docs-relative
// path, used for the edit link and in error messages.
func ParsePage(src, rel string, cfg Config) (Page, error) {
	lines := strings.Split(src, "\n")
	start := skipPreamble(lines)

	titleAt := findTitle(lines, start)
	if titleAt < 0 {
		return Page{}, fmt.Errorf("%s: no # title", rel)
	}
	rest := lines[titleAt+1:]
	for len(rest) > 0 && strings.TrimSpace(rest[0]) == "" {
		rest = rest[1:]
	}

	desc := firstParagraph(rest)
	if desc == "" {
		return Page{}, fmt.Errorf("%s: no prose paragraph to use as the description", rel)
	}
	heading := atxClosingRe.ReplaceAllString(strings.TrimPrefix(lines[titleAt], "# "), "")
	page := Page{
		Title:       plainText(heading),
		Description: truncate(desc, maxDescription),
		EditURL:     cfg.EditBase + "/" + rel,
		Body:        strings.Join(rest, "\n"),
	}
	if strings.HasPrefix(strings.TrimSpace(src), generatedMarker) {
		page.EditURL = ""
		page.Body = generatedNote + "\n\n" + page.Body
	}
	return page, nil
}

// Frontmatter renders the page's YAML frontmatter block.
func (p Page) Frontmatter() string {
	var b strings.Builder
	b.WriteString("---\n")
	b.WriteString("title: " + yamlString(p.Title) + "\n")
	b.WriteString("description: " + yamlString(p.Description) + "\n")
	if p.EditURL == "" {
		b.WriteString("editUrl: false\n")
	} else {
		b.WriteString("editUrl: " + yamlString(p.EditURL) + "\n")
	}
	b.WriteString("---\n")
	return b.String()
}

// Transform turns one docs page into a Starlight content page: frontmatter
// followed by the body with its links rewritten.
func Transform(src, rel string, cfg Config) (string, error) {
	page, err := ParsePage(src, rel, cfg)
	if err != nil {
		return "", err
	}
	body, err := RewriteLinks(page.Body, rel, cfg)
	if err != nil {
		return "", err
	}
	return page.Frontmatter() + "\n" + body, nil
}

// skipPreamble returns the index of the first line that is neither blank nor
// part of a leading HTML comment.
func skipPreamble(lines []string) int {
	i := 0
	for i < len(lines) {
		t := strings.TrimSpace(lines[i])
		switch {
		case t == "":
			i++
		case strings.HasPrefix(t, "<!--"):
			for i < len(lines) && !strings.Contains(lines[i], "-->") {
				i++
			}
			i++
		default:
			return i
		}
	}
	return i
}

// atxClosingRe matches an ATX heading's optional closing sequence: a run of #
// after whitespace at the end of the line. A # inside the text, as in "C#",
// is not one.
var atxClosingRe = regexp.MustCompile(`\s+#+\s*$`)

// findTitle returns the index of the first ATX H1 outside fenced code at or
// after start, or -1.
func findTitle(lines []string, start int) int {
	var f fence
	for i := start; i < len(lines); i++ {
		if f.step(lines[i]) || f.open() {
			continue
		}
		if strings.HasPrefix(lines[i], "# ") {
			return i
		}
	}
	return -1
}

// firstParagraph returns the first prose paragraph in lines as plain text, or
// "" if there is none. Headings, quotes, lists, tables, HTML, asides, and code
// are skipped.
func firstParagraph(lines []string) string {
	var block []string
	var f fence
	for _, line := range lines {
		if f.step(line) {
			if p := proseOf(block); p != "" {
				return p
			}
			block = nil
			continue
		}
		if f.open() {
			continue
		}
		if strings.TrimSpace(line) == "" {
			if p := proseOf(block); p != "" {
				return p
			}
			block = nil
			continue
		}
		block = append(block, strings.TrimSpace(line))
	}
	return proseOf(block)
}

var (
	listStartRe = regexp.MustCompile(`^([-*+]|\d+[.)])\s`)
	refDefStart = regexp.MustCompile(`^\[[^\]]+\]:\s`)
)

// proseOf returns the block as plain text if it is a prose paragraph.
func proseOf(block []string) string {
	if len(block) == 0 {
		return ""
	}
	first := block[0]
	for _, p := range []string{"#", ">", "|", "<", "!", ":::", "---", "***", "___"} {
		if strings.HasPrefix(first, p) {
			return ""
		}
	}
	if listStartRe.MatchString(first) || refDefStart.MatchString(first) {
		return ""
	}
	return plainText(strings.Join(block, " "))
}

var plainTextRules = []struct {
	re   *regexp.Regexp
	repl string
}{
	{regexp.MustCompile(`!\[[^\]]*\]\([^)]*\)`), ""},
	{regexp.MustCompile(`\[([^\]]*)\]\([^)]*\)`), "$1"},
	{regexp.MustCompile(`\[([^\]]*)\]\[[^\]]*\]`), "$1"},
	{regexp.MustCompile(`\*\*([^*]+)\*\*`), "$1"},
	{regexp.MustCompile(`__([^_]+)__`), "$1"},
	{regexp.MustCompile(`\*([^*\s][^*]*)\*`), "$1"},
	{regexp.MustCompile(`(^|\W)_([^_\s][^_]*)_(\W|$)`), "$1$2$3"},
	{regexp.MustCompile(`</?[A-Za-z][^>]*>|<!--.*?-->`), ""},
	{regexp.MustCompile(`\s+`), " "},
}

// codeSlotRe matches the placeholder plainText puts where a code span was.
var codeSlotRe = regexp.MustCompile("\x00([0-9]+)\x00")

// plainText strips inline Markdown (links, images, code, emphasis, HTML) and
// collapses whitespace. Code spans are set aside first and restored last, so
// their contents come through verbatim: <name> is not a tag, *a* is not
// emphasis.
func plainText(md string) string {
	var b strings.Builder
	var code []string
	last := 0
	for _, sp := range codeSpans(md) {
		b.WriteString(md[last:sp.start])
		b.WriteString("\x00" + strconv.Itoa(len(code)) + "\x00")
		code = append(code, md[sp.inner:sp.innerEnd])
		last = sp.end
	}
	b.WriteString(md[last:])
	md = b.String()

	for _, r := range plainTextRules {
		md = r.re.ReplaceAllString(md, r.repl)
	}
	md = codeSlotRe.ReplaceAllStringFunc(md, func(slot string) string {
		i, _ := strconv.Atoi(slot[1 : len(slot)-1])
		return code[i]
	})
	return strings.TrimSpace(md)
}

// truncate shortens s to at most limit runes, cutting at a word boundary and
// ending with an ellipsis.
func truncate(s string, limit int) string {
	if utf8.RuneCountInString(s) <= limit {
		return s
	}
	runes := []rune(s)[:limit-1]
	if cut := strings.LastIndex(string(runes), " "); cut > len(string(runes))/2 {
		runes = []rune(string(runes)[:cut])
	}
	return strings.TrimRight(string(runes), " ,;:.") + "…"
}

// yamlString renders s as a double-quoted YAML scalar. JSON string syntax is
// valid YAML; HTML escaping is turned off so <, >, and & stay readable.
func yamlString(s string) string {
	var buf bytes.Buffer
	enc := json.NewEncoder(&buf)
	enc.SetEscapeHTML(false)
	if err := enc.Encode(s); err != nil {
		return `""`
	}
	return strings.TrimSuffix(buf.String(), "\n")
}
