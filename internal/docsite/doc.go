// Package docsite turns the canonical Markdown under docs/ into the content tree
// the Astro + Starlight site in website/ builds from.
//
// docs/ is the single source of truth and is only ever read here. The site
// content (website/src/content/docs) and the sidebar and install data
// (website/src/generated) are gitignored and rebuilt by `go run ./cmd/gen-site`.
// The one tracked output is the install-methods region of README.md, kept
// byte-identical to the region in docs/installation.md.
//
// The pipeline:
//
//   - nav.go: parse and validate docs/nav.yaml, and check every page is either
//     listed or excluded.
//   - slug.go: map a docs-relative path to its site slug.
//   - markdown.go: derive Starlight frontmatter (title, description, editUrl)
//     and mark pages generated by cmd/gen-reference.
//   - links.go: rewrite relative links to site URLs or GitHub blob URLs, and
//     fail on targets that do not exist.
//   - install.go: parse the install-methods region and render the README block
//     and the JSON the InstallTabs component reads.
//   - sidebar.go: build the Starlight sidebar from the manifest.
//   - generate.go: assemble a Plan, then Write it or Check it for drift.
